-- Số liệu tổng hợp cho trang tổng quan (khỏi phải tải cả ngân hàng câu hỏi về đếm).
drop view if exists public.module_stats;
create view public.module_stats
with (security_invoker = on) as
select
  module_id,
  count(*)::int                                                                      as total,
  count(*) filter (where kind = 'mc')::int                                           as mc_total,
  count(*) filter (where kind = 'essay')::int                                        as essay_total,
  count(*) filter (where kind = 'mc' and answer is not null)::int                    as with_answer,
  count(*) filter (where kind = 'mc' and answer is not null
                     and jsonb_array_length(options) > 0)::int                       as answerable,
  count(*) filter (where multi)::int                                                 as multi_total
from public.questions
group by module_id;

