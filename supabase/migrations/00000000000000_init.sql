-- Mức thành thạo theo từng chủ đề, dùng vẽ biểu đồ mạng nhện. RLS lọc theo người dùng.
drop view if exists public.topic_mastery;
create view public.topic_mastery
with (security_invoker = on) as
select
  r.user_id,
  r.module_id,
  q.topic_id,
  t.name  as topic_name,
  t.slug  as topic_slug,
  count(*)::int                                                   as answered,
  count(*) filter (where r.correct)::int                           as correct,
  round(avg(case when r.correct then 1 else 0 end) * 100)::int     as pct,
  round(avg(r.time_ms))::int                                       as avg_time_ms
from public.responses r
join public.questions q
  on q.module_id = r.module_id and q.stage_id = r.stage_id and q.n = r.question_n
left join public.topics t on t.id = q.topic_id
group by r.user_id, r.module_id, q.topic_id, t.name, t.slug;

-- ---------------------------------------------------------------- 6. phân tích chất lượng câu hỏi

-- Chỉ quản trị viên đọc được, nên dùng SECURITY DEFINER kèm kiểm tra is_admin()
-- thay vì view thường (view không gắn được RLS).
create or replace function public.item_analysis(p_module text)
returns table (
  question_n     int,
  n              int,
  p_value        numeric,   -- tỷ lệ trả lời đúng: càng cao càng dễ
  discrimination numeric,   -- chênh lệch nhóm giỏi - nhóm yếu, < 0.2 là câu kém
  avg_time_ms    int
)
language sql
security definer stable set search_path = public
as $$
  with ability as (
    select user_id, avg(case when correct then 1 else 0 end) as score
    from public.responses where module_id = p_module group by user_id
  ),
  ranked as (
    select r.question_n, r.correct, r.time_ms,
           ntile(4) over (order by a.score) as quartile
    from public.responses r
    join ability a using (user_id)
    where r.module_id = p_module
  )
  select
    question_n,
    count(*)::int,
    round(avg(case when correct then 1 else 0 end)::numeric, 3),
    round((
      coalesce(avg(case when quartile = 4 then (case when correct then 1 else 0 end) end), 0)
      - coalesce(avg(case when quartile = 1 then (case when correct then 1 else 0 end) end), 0)
    )::numeric, 3),
    round(avg(time_ms))::int
  from ranked
  where public.is_admin()
  group by question_n
  order by 3 asc;
$$;

-- Tỷ lệ chọn từng phương án — phát hiện câu có đáp án sai hoặc gây nhầm lẫn.
create or replace function public.option_picks(p_module text, p_n int)
returns table (chosen text, n int)
language sql
security definer stable set search_path = public
as $$
  select chosen, count(*)::int
  from public.responses
  where module_id = p_module and question_n = p_n
    and chosen is not null and chosen <> ''
    and public.is_admin()
  group by chosen
  order by 2 desc;
$$;

