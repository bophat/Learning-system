-- ---------------------------------------------------------------- questions

create table if not exists public.questions (
  id          bigint generated by default as identity primary key,
  module_id   text not null references public.exam_modules(id) on delete cascade,
  /*
   * Cấp độ (N1, N2...) khi chứng chỉ có chia cấp — rỗng nếu không. Cùng với
   * stage_id, hai cột này xác định ĐÚNG một câu hỏi: một chứng chỉ có thể có
   * nhiều cấp, mỗi cấp có nhiều chặng thi, mỗi chặng đánh số câu từ 1.
   */
  level_id    text not null default '',
  stage_id    text not null default 'exam',
  n           int  not null,
  /*
   * 8 dạng câu hỏi. Bốn dạng đầu dùng các cột cố định bên dưới; bốn dạng mới
   * (listening/reading/writing/matching/accounting) dùng thêm cột `payload`
   * — JSONB tự do vì mỗi dạng có hình dạng dữ liệu khác hẳn nhau (audio +
   * phần/tổng phần, đoạn văn + nhiều câu con lồng nhau, số từ tối thiểu, cặp
   * ghép nối, bút toán debit/credit). Ràng buộc kiểu chặt nằm ở phía
   * TypeScript (`src/types/exam.ts`), không ở CSDL — xem chú thích payload.
   */
  kind        text not null default 'mc'
              check (kind in ('mc', 'essay', 'flashcard', 'listening', 'reading', 'writing', 'matching', 'accounting')),

  -- câu trắc nghiệm (dùng chung cho 'mc' và 'listening' — nghe xong vẫn chấm như trắc nghiệm)
  stem_en     text,
  stem_ja     text,
  options     jsonb not null default '[]'::jsonb,   -- [{label,en,ja,why?}]
  answer      text,
  multi       boolean not null default false,
  domain      text,

  -- câu tự luận (cũng dùng cho 'writing' — prompt ở đây, minWords/sampleAnswer trong payload)
  title         text,
  prompt        text,
  sub_questions jsonb not null default '[]'::jsonb, -- [{id,prompt,referenceAnswer}] (essay) hoặc câu con lồng trong 'reading'
  required      boolean not null default false,

  /*
   * Payload theo từng kind — UI đọc đúng theo `kind`, không đoán:
   *   listening : {part, totalParts, revealAfterAudio}
   *   reading   : {passageEn, passageJa} — sub_questions chứa các câu con,
   *               mỗi câu con tự có "kind": "mc" | "completion" | "matching"
   *   writing   : {minWords, sampleAnswer?}
   *   matching  : {items: [{id,label,options:[string],answerIndex}]}
   *   accounting: {accounts:[string], correctEntries:[{side:"debit"|"credit",account,amount}]}
   */
  payload     jsonb not null default '{}'::jsonb,

  created_at  timestamptz not null default now(),
  unique (module_id, level_id, stage_id, n)
);
alter table public.questions add column if not exists payload jsonb not null default '{}'::jsonb;
-- Xoá rồi tạo lại là cách "thêm ràng buộc nếu chưa có" trong Postgres — an
