create table if not exists public.question_highlights (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references auth.users on delete cascade,
  module_id    text not null,
  level_id     text not null default '',
  stage_id     text not null default '',
  question_n   int  not null,
  /*
   * Trường văn bản chứa đoạn được tô, ví dụ "stem_en", "stem_ja", "option_A",
   * "explanation". Cho phép rỗng vì bản UI hiện tại xác định vị trí tô bằng
   * DOM Range của trình duyệt tại thời điểm chọn, chưa gửi lên tên trường cụ
   * thể — để trống thay vì bắt buộc, tránh chặn phần đã làm.
   */
  field        text not null default '',
  -- Vị trí ký tự (UTF-16 code unit, tức string.length của JS) trong trường
  -- văn bản nguồn — CHO PHÉP NULL vì lý do tương tự trên. Có offset thì vẽ
  -- lại highlight chính xác sau khi tải lại trang; không có thì chỉ hiện
  -- được trong sổ tay ghi chú, không vẽ lại được đúng vị trí trong đề bài.
  start_offset int check (start_offset is null or start_offset >= 0),
  end_offset   int check (end_offset is null or start_offset is null or end_offset > start_offset),
  -- Màu tô — độc lập với "kind" (phân loại). UI hiện có 4 màu.
  color        text not null default 'yellow' check (color in ('yellow', 'green', 'pink', 'blue')),
  -- Nguyên văn đoạn đã tô.
  quote        text not null check (length(quote) between 1 and 600),
  kind         text not null default 'note' check (kind in ('vocab', 'formula', 'tip', 'note')),
  -- Ghi chú đính kèm; rỗng nghĩa là chỉ tô màu, không viết gì thêm.
  note         text not null default '' check (length(note) <= 2000),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

