create table if not exists public.question_state (
  user_id     uuid not null references auth.users on delete cascade,
  module_id   text not null,
  /*
   * level_id + stage_id cùng module_id + question_n mới xác định đúng MỘT
   * câu hỏi. Thiếu hai cột này thì câu 1 buổi sáng và câu 1 buổi chiều của
   * AP (cùng module, cùng số câu, khác stage) sẽ ghi đè trạng thái của nhau —
   * đánh dấu "đã thuộc" câu 1 buổi sáng sẽ lây sang câu 1 buổi chiều. Thêm
   * cấp độ (JLPT N1..N5, mỗi cấp đều đánh số câu từ 1) sẽ nhân lỗi này lên
   * gấp bội nếu không sửa ở đây trước.
   */
  level_id    text not null default '',
  stage_id    text not null default '',
  question_n  int  not null,
  bookmarked  boolean not null default false,
  status      text check (status in ('wrong', 'mastered')),
  updated_at  timestamptz not null default now(),
  primary key (user_id, module_id, level_id, stage_id, question_n)
);
-- Cột ghi chú và các cột SM-2 (due_at, ease, reps...) được thêm bên dưới,
-- ở phần "Sáu trụ cột học tập" — không lặp lại ở đây.
-- Cho CSDL đã có bảng question_state từ trước phần vá lỗi đụng số này.
alter table public.question_state add column if not exists level_id text not null default '';
alter table public.question_state add column if not exists stage_id text not null default '';
-- Bảng đã tồn tại từ trước có thể còn khoá chính 3 cột cũ (thiếu level_id,
-- stage_id) — dựng lại cho đủ 5 cột nếu vậy. Bảng mới tạo ở trên đã đúng sẵn.
do $$
declare pk_cols int;
begin
  select array_length(conkey, 1) into pk_cols
  from pg_constraint
  where conname = 'question_state_pkey' and conrelid = 'public.question_state'::regclass;

  if pk_cols is not null and pk_cols < 5 then
    alter table public.question_state drop constraint question_state_pkey;
    alter table public.question_state add constraint question_state_pkey
      primary key (user_id, module_id, level_id, stage_id, question_n);
  end if;
end $$;

create index if not exists question_state_user_idx on public.question_state (user_id, module_id);

