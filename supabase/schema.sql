--  PHẦN 3 — Ghi chú theo đoạn văn bản được tô chọn (highlight)
--
--  Khác với question_state.note (MỘT ô ghi chú cho cả câu), đây là NHIỀU
--  điểm ghi chú gắn vào đúng đoạn văn bản người học bôi đen bằng chuột —
--  từ vựng, công thức, hay bất kỳ đoạn nào trong đề bài / phương án / giải
--  thích. Giống cách Kindle hay Medium highlight văn bản.
