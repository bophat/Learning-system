  for update using (id = auth.uid()) with check (id = auth.uid());

/*
 * Chặn tự nâng quyền.
 *
 * Policy ở trên chỉ giới hạn được DÒNG nào sửa được, không giới hạn được CỘT —
 * nếu để nguyên thì người dùng thường sửa hồ sơ của chính mình và đổi luôn
 * `role` thành 'admin'. Hai lớp chặn:
 *   1. Quyền theo cột: `authenticated` chỉ được cập nhật `display_name`.
 *   2. Trigger: chặn mọi thay đổi `role` không đến từ admin hoặc service_role.
 */
revoke update on public.profiles from authenticated;
grant update (display_name) on public.profiles to authenticated;

create or replace function public.prevent_role_escalation()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.role is distinct from old.role
     and current_user <> 'service_role'
     and not public.is_admin() then
    raise exception 'Chỉ quản trị viên mới được đổi vai trò tài khoản';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_no_role_escalation on public.profiles;
create trigger profiles_no_role_escalation
  before update on public.profiles
  for each row execute function public.prevent_role_escalation();

